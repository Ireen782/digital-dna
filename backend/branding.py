import os

BRAND_NAME = "Digital DNA"
TAGLINE = "Upload. Investigate. Verify."
LOGO_PATH = os.path.join(os.path.dirname(__file__), "assets", "logo.png")

PURPLE = (0.357, 0.165, 0.620)
DARK_PURPLE = (0.227, 0.102, 0.400)
GREY = (0.4, 0.4, 0.45)


def logo_exists():
    return os.path.exists(LOGO_PATH)


def draw_pdf_page(canvas, doc):
    """Draws the Digital DNA header and footer on every PDF page."""
    from reportlab.lib.pagesizes import A4
    from reportlab.pdfbase.pdfmetrics import stringWidth

    width, height = A4
    canvas.saveState()

    text_x = 40
    if logo_exists():
        canvas.drawImage(
            LOGO_PATH, 36, height - 62, width=44, height=44,
            mask="auto", preserveAspectRatio=True,
        )
        text_x = 90

    canvas.setFillColorRGB(*DARK_PURPLE)
    canvas.setFont("Helvetica", 18)
    canvas.drawString(text_x, height - 40, "Digital ")
    offset = stringWidth("Digital ", "Helvetica", 18)
    canvas.setFont("Helvetica-Bold", 18)
    canvas.drawString(text_x + offset, height - 40, "DNA")

    canvas.setFillColorRGB(*GREY)
    canvas.setFont("Helvetica", 9)
    canvas.drawString(text_x, height - 55, TAGLINE)

    canvas.setStrokeColorRGB(*PURPLE)
    canvas.setLineWidth(2)
    canvas.line(36, height - 70, width - 36, height - 70)

    canvas.setFillColorRGB(*GREY)
    canvas.setFont("Helvetica", 8)
    canvas.drawString(
        40, 28, "Generated by Digital DNA. Evidence-based assessment, not absolute proof."
    )
    canvas.drawRightString(width - 40, 28, f"Page {doc.page}")
    canvas.restoreState()